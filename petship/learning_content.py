def lesson_body(slug: str, title: str, summary: str | None) -> str:
    """Return a practical, topic-specific lesson body."""
    practice = LESSON_PRACTICES.get(slug, {}).get(title)
    if practice is None:
        practice = (
            f"Choose one small, safe action related to {title.lower()}, practise it "
            "briefly at a calm time, and record what your pet is comfortable with. "
            "Pause if your pet shows stress and ask a veterinarian or qualified "
            "trainer when you need individual advice."
        )
    opening = (summary or "").strip()
    return f"{opening}\n\n{practice}" if opening else practice
